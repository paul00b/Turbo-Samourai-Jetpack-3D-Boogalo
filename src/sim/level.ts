export function parseLevel(rows: readonly string[]): Level {
  const height = rows.length;
  const width = rows[0].length;
  const tiles = new Uint8Array(width * height);
  const enemies: EnemySpawn[] = [];
  let spawnX = TILE_SIZE * 2;
  let spawnY = TILE_SIZE * 2;
  for (let y = 0; y < height; y++) {
    const row = rows[y];
    if (row.length !== width) throw new Error(`Ligne ${y} : largeur ${row.length}, attendu ${width}`);
    for (let x = 0; x < width; x++) {
      const c = row[x];
      let t = T_AIR;
      switch (c) {
        case '#':
          t = T_SOLID;
          break;
        case '=':
          t = T_SLICK;
          break;
        case '^':
          t = T_SPIKE;
          break;
        case 'S':
          spawnX = x * TILE_SIZE + TILE_SIZE / 2;
          spawnY = y * TILE_SIZE + TILE_SIZE / 2;
          break;
        case 'e':
        case 'p':
          enemies.push({
            x: x * TILE_SIZE + TILE_SIZE / 2,
            y: y * TILE_SIZE + TILE_SIZE / 2 + 2,
            w: 24,
            h: 28,
            patrol: c === 'p',
          });
          break;
        default:
          break;
      }
      tiles[y * width + x] = t;
    }
  }
  return { width, height, tiles, spawnX, spawnY, enemies, labels: ZONE_LABELS };
}

/** Registre des niveaux : la sim référence un niveau par id (state.levelId), jamais par objet. */
export const LEVELS: readonly Level[] = [parseLevel(MAP_ROWS)];

export function getLevel(id: number): Level {
  return LEVELS[id] ?? LEVELS[0];
}

/** Hors map = plein non accrochable. */
export function tileAt(level: Level, tx: number, ty: number): number {
  if (tx < 0 || ty < 0 || tx >= level.width || ty >= level.height) return T_SLICK;
  return level.tiles[ty * level.width + tx];
}

export function isSolidTile(t: number): boolean {
  return t === T_SOLID || t === T_SLICK;
}

export interface RayHit {
  hit: boolean;
  dist: number;
  x: number;
  y: number;
  tile: number;
  nx: number;
  ny: number;
}

export function makeRayHit(): RayHit {
  return { hit: false, dist: 0, x: 0, y: 0, tile: T_AIR, nx: 0, ny: 0 };
}

/**
 * Lancer de rayon dans la grille (Amanatides & Woo). `dx, dy` unitaire. Arrête au premier tile
 * non vide (plein, lisse ou pic) rencontré avant `maxDist`. Déterministe : + - * / floor uniquement.
 */
export function raycastTiles(
  level: Level,
  ox: number,
  oy: number,
  dx: number,
  dy: number,
  maxDist: number,
  out: RayHit,
): RayHit {
  out.hit = false;
  const ts = TILE_SIZE;
  let tx = Math.floor(ox / ts);
  let ty = Math.floor(oy / ts);
  const startTile = tileAt(level, tx, ty);
  if (startTile !== T_AIR) {
    out.hit = true;
    out.dist = 0;
    out.x = ox;
    out.y = oy;
    out.tile = startTile;
    out.nx = -dx;
    out.ny = -dy;
    return out;
  }
  const stepX = dx > 0 ? 1 : dx < 0 ? -1 : 0;
  const stepY = dy > 0 ? 1 : dy < 0 ? -1 : 0;
  const tDeltaX = stepX !== 0 ? ts / (dx < 0 ? -dx : dx) : Infinity;
  const tDeltaY = stepY !== 0 ? ts / (dy < 0 ? -dy : dy) : Infinity;
  let tMaxX =
    stepX > 0 ? ((tx + 1) * ts - ox) / dx : stepX < 0 ? (tx * ts - ox) / dx : Infinity;
  let tMaxY =
    stepY > 0 ? ((ty + 1) * ts - oy) / dy : stepY < 0 ? (ty * ts - oy) / dy : Infinity;
  // Garde-fou : jamais plus de cases que la diagonale de la map.
  const maxSteps = level.width + level.height + 2;
  for (let i = 0; i < maxSteps; i++) {
    let t: number;
    let nx = 0;
    let ny = 0;
    if (tMaxX < tMaxY) {
      t = tMaxX;
      tx += stepX;
      tMaxX += tDeltaX;
      nx = -stepX;
    } else {
      t = tMaxY;
      ty += stepY;
      tMaxY += tDeltaY;
      ny = -stepY;
    }
    if (t > maxDist) return out;
    const tile = tileAt(level, tx, ty);
    if (tile !== T_AIR) {
      out.hit = true;
      out.dist = t;
      out.x = ox + dx * t;
      out.y = oy + dy * t;
      out.tile = tile;
      out.nx = nx;
      out.ny = ny;
      return out;
    }
  }
  return out;
}
