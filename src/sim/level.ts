export const T_AIR = 0;
export const T_SOLID = 1;
export const T_SLICK = 2; // plein, non accrochable
export const T_SPIKE = 3;

/** Inset de la hitbox des pics (en px) pour être un peu tolérant aux frôlements. */
export const SPIKE_INSET = 6;

export interface EnemySpawn {
  x: number; // centre, px
  y: number;
  w: number;
  h: number;
  patrol: boolean;
}

export interface ZoneLabel {
  name: string;
  x: number; // tuiles
  y: number;
}

export interface Level {
  width: number; // en tuiles
  height: number;
  tiles: Uint8Array; // width*height, indexé [y*width + x]
  spawnX: number; // px, centre du joueur
  spawnY: number;
  enemies: readonly EnemySpawn[];
  labels: readonly ZoneLabel[];
}

